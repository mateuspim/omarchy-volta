import assert from "node:assert/strict"
import fs from "node:fs"
import vm from "node:vm"

const source = fs.readFileSync(new URL("../Model.js", import.meta.url), "utf8")
  .replace(/^\.pragma library\s*/m, "")
const model = {}
vm.runInNewContext(source + "\nObject.assign(model, { clamp, clampVolume, percent, channelName, parseSinkAvailability, stereoIndices, readStereo, withStereoVolumes, balance, applyBalance, balanceLabel, safeSinkText, sinkLabel, isOverGain, gainSplit, balanceSpan, meterSegment, heroMeta, heroDetail, footerHints, nodeProps, plainSinkLabel, sinkConnection, sinkKind, sinkEntry, visibleOutputs });", { model, isFinite })

assert.equal(model.clampVolume(-1), 0)
assert.equal(model.clampVolume(2), 1.5)
assert.equal(model.percent(1.234), "123%")
assert.deepEqual({ ...model.parseSinkAvailability("sink.a\t1\nsink.b\t0\n") }, { "sink.a": true, "sink.b": false })

const fixture = name => JSON.parse(fs.readFileSync(new URL(`fixtures/${name}.json`, import.meta.url), "utf8"))
const stereoFixture = fixture("stereo")
const monoFixture = fixture("mono")
const surroundFixture = fixture("surround")
const channels = stereoFixture.channels
assert.deepEqual({ ...model.stereoIndices(channels) }, { left: 0, right: 1, mono: -1 })
assert.deepEqual({ ...model.stereoIndices(["PwAudioChannel.FrontRight", "PwAudioChannel.FrontLeft"]) }, { left: 1, right: 0, mono: -1 })

const stereo = model.readStereo(channels, stereoFixture.volumes)
assert.equal(stereo.supported, true)
assert.equal(stereo.left, 0.65)
assert.equal(stereo.right, 0.8)
assert.equal(model.readStereo(monoFixture.channels, monoFixture.volumes).mono, true)
assert.equal(model.readStereo(surroundFixture.channels, surroundFixture.volumes).supported, true)
assert.equal(model.readStereo(["RearLeft", "RearRight"], [1, 1]).supported, false)

assert.deepEqual(Array.from(model.withStereoVolumes([0.2, 0.3, 0.4], 0, 2, 2, -1)), [1.5, 0.3, 0])
assert.equal(model.balance(1, 1), 0)
assert.equal(model.balance(0.5, 1), 0.5)
assert.equal(model.balance(1, 0.25), -0.75)
assert.deepEqual({ ...model.applyBalance(0.2, 0.8, 0) }, { left: 0.8, right: 0.8 })
assert.deepEqual({ ...model.applyBalance(1, 1, -0.5) }, { left: 1, right: 0.5 })
assert.deepEqual({ ...model.applyBalance(0, 0, 0.5) }, { left: 0, right: 0 })
assert.equal(model.balanceLabel(0), "Center")
assert.equal(model.balanceLabel(-0.42), "42% left")
assert.equal(model.sinkLabel({ description: "Speakers" }), "Speakers")
assert.equal(model.sinkLabel({ description: "", nickname: "Headphones" }), "Headphones")
assert.equal(model.sinkLabel({ description: '<img src="file:///etc/passwd"> & speakers' }), '&lt;img src="file:///etc/passwd"&gt; & speakers')
assert.equal(model.sinkLabel({ description: '<img src="https://example.com/pixel">' }).includes("<"), false)
assert.equal(model.sinkLabel({ description: "B&O Beoplay" }), "B&O Beoplay")
assert.equal(model.safeSinkText("x".repeat(200)).length, 160)


assert.equal(model.isOverGain(1), false)
assert.equal(model.isOverGain(1.05), true)
const near = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`)
near(model.gainSplit(0.75).normal, 0.5)
near(model.gainSplit(0.75).over, 0)
near(model.gainSplit(1.2).normal, 2 / 3)
near(model.gainSplit(1.2).over, 0.2 / 1.5)
near(model.gainSplit(9).over, 1 / 3)
assert.deepEqual({ ...model.balanceSpan(0) }, { from: 0.5, to: 0.5 })
assert.deepEqual({ ...model.balanceSpan(-0.5) }, { from: 0.25, to: 0.5 })
assert.deepEqual({ ...model.balanceSpan(2) }, { from: 0.5, to: 1 })
assert.equal(model.meterSegment(0, 0.64), "lit")
assert.equal(model.meterSegment(6, 0.64), "off")
assert.equal(model.meterSegment(10, 1.18), "over")
assert.equal(model.meterSegment(12, 1.18), "zone")
assert.equal(model.meterSegment(9, 1), "lit")
assert.equal(model.meterSegment(10, 1), "zone")
assert.equal(model.heroMeta(false, false), "No output available")
assert.equal(model.heroMeta(true, false), "Stereo output")
assert.equal(model.heroMeta(true, true), "Mono output")
assert.equal(model.heroDetail(true, true, 0.4, true), "Muted")
assert.equal(model.heroDetail(false, true, 0.4, true), "Linked")
assert.equal(model.heroDetail(false, false, 0.46, true), "46% right")
assert.equal(model.heroDetail(false, false, 0.46, false), "")
assert.deepEqual(Array.from(model.footerHints(true), h => h.label), ["output", "link", "mute", "reset", "close"])
assert.deepEqual(Array.from(model.footerHints(false), h => h.label), ["output", "mute", "reset", "close"])

assert.deepEqual({ ...model.nodeProps({ ready: false, properties: { a: 1 } }) }, {})
assert.deepEqual({ ...model.nodeProps({ ready: true, properties: { a: 1 } }) }, { a: 1 })
assert.equal(model.plainSinkLabel({ description: "<b>Desk</b>" }), "<b>Desk</b>")
assert.equal(model.sinkConnection({ "device.api": "bluez5" }, "bluez_output.sample.1"), "Bluetooth")
assert.equal(model.sinkConnection({}, "bluez_output.sample.1"), "Bluetooth")
assert.equal(model.sinkConnection({ "device.api": "alsa", "device.bus": "pci", "device.profile.name": "hdmi-stereo" }, "alsa_output.pci-0000_01_00.1.hdmi-stereo"), "HDMI")
assert.equal(model.sinkConnection({ "device.api": "alsa", "device.profile.description": "DisplayPort 2" }, "alsa_output.x"), "DisplayPort")
assert.equal(model.sinkConnection({ "device.api": "alsa", "device.bus": "usb" }, "alsa_output.usb-x.analog-stereo"), "USB")
assert.equal(model.sinkConnection({ "device.api": "alsa", "device.bus": "pci" }, "alsa_output.pci-x.analog-stereo"), "Built-in")
assert.equal(model.sinkConnection({ "factory.name": "support.null-audio-sink" }, "effect_input.sample"), "Virtual")
assert.equal(model.sinkConnection({}, ""), "")
assert.equal(model.sinkKind({ "device.form-factor": "headphone" }, "Studio", "USB"), "headphones")
assert.equal(model.sinkKind({}, "Wireless Earbuds", "Bluetooth"), "headphones")
assert.equal(model.sinkKind({}, "Living Room TV", "HDMI"), "display")
assert.equal(model.sinkKind({ "device.form-factor": "speaker" }, "Desk", "Built-in"), "speakers")
assert.equal(model.sinkKind({}, "Portable Speaker", "Bluetooth"), "speakers")
assert.equal(model.sinkKind({}, "Car kit", "Bluetooth"), "bluetooth")
assert.equal(model.sinkKind({}, "DAC", "USB"), "usb")
assert.equal(model.sinkKind({}, "Effects", "Virtual"), "generic")
const headphones = model.sinkEntry({ id: 41, name: "alsa_output.usb-sample", description: "Studio Headphones" },
  { "device.api": "alsa", "device.bus": "usb", "device.form-factor": "headphone" }, ["FrontLeft", "FrontRight"], true)
assert.equal(headphones.id, "41")
assert.equal(headphones.kind, "headphones")
assert.equal(headphones.glyph, "󰋋")
assert.equal(headphones.subtitle, "USB")
assert.equal(headphones.active, true)
assert.equal(headphones.stereo, true)
const speakerphone = model.sinkEntry({ id: 43, name: "alsa_output.usb-phone", description: "Speakerphone" }, { "device.api": "alsa", "device.bus": "usb" }, ["Mono"], false)
assert.equal(speakerphone.subtitle, "USB · mono")
assert.equal(speakerphone.stereo, false)
assert.equal(model.sinkEntry({ id: 7, name: "x" }, { "device.api": "alsa", "device.bus": "pci" }, ["RearLeft", "RearRight"], false).subtitle, "Built-in · no stereo")
assert.equal(model.sinkEntry({ id: 8, name: "x" }, { "device.api": "alsa", "device.bus": "pci" }, [], false).subtitle, "Built-in")
const outputs = n => Array.from({ length: n }, (_, i) => ({ id: String(i), active: false }))
const three = outputs(3)
assert.equal(model.visibleOutputs(three, false).rows.length, 3)
assert.equal(model.visibleOutputs(three, false).overflow, false)
const six = outputs(6)
six[0].active = true
assert.deepEqual(Array.from(model.visibleOutputs(six, false).rows, r => r.id), ["0", "1", "2"])
assert.equal(model.visibleOutputs(six, false).hidden, 3)
six[0].active = false; six[3].active = true
assert.deepEqual(Array.from(model.visibleOutputs(six, false).rows, r => r.id), ["2", "3", "4"])
six[3].active = false; six[5].active = true
assert.deepEqual(Array.from(model.visibleOutputs(six, false).rows, r => r.id), ["3", "4", "5"])
assert.equal(model.visibleOutputs(six, true).rows.length, 6)
assert.equal(model.visibleOutputs(six, true).hidden, 0)
assert.equal(model.visibleOutputs(six, true).overflow, true)
console.log("Model tests passed")
